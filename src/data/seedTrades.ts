/**
 * Builds processed seed trades with accurate charges and pnl
 */
export function generateSeedTrades(): Trade[] {
  return RAW_TRADES.map((item) => {
    const gross_pnl = calculateGrossPnL(
      item.side,
      item.lots,
      item.lot_size,
      item.entry_price,
      item.exit_price
    );

    const charges = calculateEstimatedCharges(
      {
        segment: item.segment,
        symbol: item.symbol,
        side: item.side,
        lots: item.lots,
        lot_size: item.lot_size,
        entry_price: item.entry_price,
        exit_price: item.exit_price,
      },
      DEFAULT_CHARGES_SETTINGS
    );

    const net_pnl = Math.round((gross_pnl - charges) * 100) / 100;
    const hold_time = calculateHoldTime(item.entry_time, item.exit_time);

    return {
      ...item,
      gross_pnl,
      charges,
      net_pnl,
      hold_time,
    };
  });
}
